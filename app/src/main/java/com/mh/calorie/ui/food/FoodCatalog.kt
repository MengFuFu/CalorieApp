object FoodCatalog {

    /** 把「名:热量|名:热量」解析成列表 */
    private fun parse(raw: String): List<FoodItem> =
        raw.trim().split("|").map { entry ->
            val i = entry.lastIndexOf(':')
            FoodItem(entry.substring(0, i).trim(), entry.substring(i + 1).trim().toInt())
        }

    /** 「名:单位」→ 第二单位表 */
    private fun parseUnits(raw: String): Map<String, String> =
        raw.trim().split("|").associate { entry ->
            val i = entry.lastIndexOf(':')
            entry.substring(0, i).trim() to entry.substring(i + 1).trim()
        }

    /** 「名:克数」→ 每个单位的重量表（毫升类就是每杯多少 ml） */
    private fun parseGrams(raw: String): Map<String, Float> =
        raw.trim().split("|").associate { entry ->
            val i = entry.lastIndexOf(':')
            entry.substring(0, i).trim() to entry.substring(i + 1).trim().toFloat()
        }

